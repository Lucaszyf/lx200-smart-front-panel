static inline int font_index_for_char(char c)
{
    switch (c) {
        case '0': return 0;  case '1': return 1;  case '2': return 2;
        case '3': return 3;  case '4': return 4;  case '5': return 5;
        case '6': return 6;  case '7': return 7;  case '8': return 8;
        case '9': return 9;  case '.': return 10; case ':': return 11;
        case '-': return 12; case '<': return 13; case '>': return 14;
        case ' ': return 15; case 'A': return 16; case 'B': return 17;
        case 'C': return 18; case 'E': return 19; case 'F': return 20;
        case 'G': return 21; case 'H': return 22; case 'I': return 23;
        case 'K': return 24; case 'M': return 25; case 'N': return 26;
        case 'O': return 27; case 'P': return 28; case 'R': return 29;
        case 'S': return 30; case 'T': return 31; case 'U': return 32;
        case 'V': return 33; case 'W': return 34; case 'Y': return 35;
        case 'i': return 36; case 'm': return 37;
        case 'o': return 38; case 'd': return 39; case 'e': return 40;
        case 'D': return 41;
        default:  return 15; // 未收录字符按空格处理，不会越界
    }
}
